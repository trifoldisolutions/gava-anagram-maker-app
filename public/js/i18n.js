let current = 'fr';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'fr';
  document.documentElement.lang = current;
}

export function getLang() {
  return current;
}

export function t(key, vars = {}) {
  const value = key.split('.').reduce((o, k) => (o ? o[k] : undefined), STRINGS[current]);
  const str = typeof value === 'string' ? value : key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export function errorText(err) {
  const code = err?.code;
  const known = code && STRINGS[current].errors[code];
  return known || err?.message || STRINGS[current].errors.generic;
}

// Fill static elements: data-i18n (text), data-i18n-ph (placeholder), data-i18n-aria / data-i18n-title.
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}
